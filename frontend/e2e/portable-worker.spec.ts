import { expect, test } from '@playwright/test'

const BACKEND = 'http://127.0.0.1:18980'
const headers = { Authorization: 'Bearer control-3-' + 'b'.repeat(32) }

test('Studio plans portable source and explicitly runs its exact reviewed draft with fresh IDs and no panel changes', async ({ page, request }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const before = await (await request.get(`${BACKEND}/test/metrics`)).json()
  const layout = await (await request.get(`${BACKEND}/api/layout`, { headers })).json()
  await page.goto('http://127.0.0.1:18981')
  await page.getByRole('button', { name: 'Connect backend' }).click()
  await page.getByLabel('Backend address').fill(BACKEND)
  await page.getByLabel('Laptop controller credential').fill('control-3-' + 'b'.repeat(32))
  await page.getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Laptop online · connected' })).toBeVisible()
  await page.locator('.assistant-options > summary').click()
  await expect(page.getByLabel('Choose minimum access automatically')).toBeChecked()
  await expect(page.getByLabel('network')).toBeDisabled()
  await page.locator('.assistant-options > summary').click()
  await page.getByLabel('AI assistant prompt').fill('fixture portable checksum')
  const outgoingPlan = page.waitForRequest(value => value.url().endsWith('/api/v1/programs/plan'))
  const generated = page.waitForResponse(value => value.url().endsWith('/api/v1/programs/generate'))
  await page.getByRole('button', { name: 'Generate', exact: true }).click()
  expect((await outgoingPlan).postDataJSON()).toEqual({ description: 'fixture portable checksum', platform: 'Linux', architecture: 'x86_64', allowed_capabilities: [] })
  const draft = await (await generated).json()
  const review = page.getByRole('dialog', { name: 'Generation complete' })
  await expect(review.getByText('Target: Linux / x86_64')).toBeVisible()
  await expect(review.getByText('Requested access: none')).toBeVisible()
  await expect(review.getByLabel('C source')).toHaveText(draft.program.source)
  expect((await (await request.get(`${BACKEND}/test/metrics`)).json()).portable_agent_jobs).toBe(before.portable_agent_jobs)
  const submission = page.waitForRequest(value => value.url().endsWith('/api/v1/agent-jobs/source'))
  await review.getByRole('button', { name: 'Run on laptop' }).click()
  const submitted = (await submission).postDataJSON()
  expect(submitted.device_id).toBe('device-3')
  expect(submitted.job_id).toMatch(/^[a-f0-9-]{36}$/)
  expect(submitted.program).toEqual(draft.program)
  expect(submitted.request).toEqual({ description: 'fixture portable checksum', operation: 'compute', platform: 'Linux', architecture: 'x86_64', capabilities: [], dependencies: [], output_protocol: 'json-v1' })
  expect(submitted).not.toHaveProperty('program_id')
  const history = page.getByRole('dialog', { name: 'Recent requests' })
  await expect(history.getByText('COMPLETED', { exact: true })).toBeVisible()
  await expect(history.getByText('42', { exact: true })).toBeVisible()
  expect(await (await request.get(`${BACKEND}/api/layout`, { headers })).json()).toEqual(layout)
  await history.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'Generate', exact: true }).click()
  await expect(review.getByRole('button', { name: 'Run on laptop' })).toBeEnabled()
  const nextSubmission = page.waitForRequest(value => value.url().endsWith('/api/v1/agent-jobs/source'))
  await review.getByRole('button', { name: 'Run on laptop' }).click()
  expect((await nextSubmission).postDataJSON().job_id).not.toBe(submitted.job_id)
  await expect(history.getByText('COMPLETED', { exact: true })).toHaveCount(2)
  const after = await (await request.get(`${BACKEND}/test/metrics`)).json()
  expect(after.planning_calls - before.planning_calls).toBe(2)
  expect(after.generation_calls - before.generation_calls).toBe(2)
  expect(after.portable_agent_jobs - before.portable_agent_jobs).toBe(2)
  expect(after.native_commands).toEqual(before.native_commands)
  expect(errors).toEqual([])
})
