import { expect, test } from '@playwright/test'

test('desktop creates and runs a panel; a paired PWA approves source reuse and receives live results', async ({ page, context, request }) => {
  const errors: string[] = []
  const generationBefore = (await (await request.get('http://127.0.0.1:18980/test/metrics')).json()).generation_calls
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('http://127.0.0.1:18981')
  await page.getByRole('button', { name: 'Connect backend' }).click()
  await page.getByLabel('Backend address').fill('http://127.0.0.1:18980')
  await page.getByLabel('Laptop controller credential').fill('control-1-' + 'b'.repeat(32))
  await page.getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(page.getByRole('button', { name: /Laptop online · connected/ })).toBeVisible()
  await page.getByRole('listitem', { name: 'Button widget', exact: true }).dragTo(page.locator('.phone-canvas'), { targetPosition: { x: 100, y: 65 } })
  await page.getByRole('tab', { name: 'Style' }).click()
  await expect(page.getByLabel('Accent role')).toHaveValue('amber')
  await page.getByLabel('Accent role').selectOption('cyan')
  await expect(page.getByRole('button', { name: 'Button', exact: true })).toHaveCSS('color', 'rgb(91, 200, 232)')
  await page.getByRole('textbox', { name: 'AI assistant prompt' }).fill('fixture')
  await page.getByRole('button', { name: 'Generate', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Run Button' })).toBeVisible()
  await page.getByLabel('Request ID').fill('studio-browser')
  await page.getByRole('button', { name: 'Generate and request execution', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Recent requests' }).getByText('COMPLETED', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  const pairing = page.waitForResponse((response) => response.url().endsWith('/api/v1/studio/pairing'))
  await page.getByRole('button', { name: 'Pair Device' }).click()
  const { code } = await (await pairing).json() as { code: string }
  await expect(page.getByRole('img', { name: 'JANUS pairing QR code' })).toBeVisible()
  await page.getByRole('button', { name: 'Close', exact: true }).click()

  const phone = await context.newPage()
  phone.on('pageerror', (error) => errors.push(error.message))
  await phone.setViewportSize({ width: 390, height: 844 })
  await phone.goto('http://127.0.0.1:18982')
  await phone.getByRole('button', { name: 'Scan to add panel' }).click()
  await phone.getByRole('button', { name: 'Enter code instead' }).click()
  await phone.getByLabel('Pairing link', { exact: true }).fill(`http://127.0.0.1:18980?pairing_code=${code}`)
  await phone.getByRole('button', { name: 'Pair', exact: true }).click()
  await phone.getByLabel('Panel name').fill('Live desk')
  await phone.getByRole('button', { name: 'Save', exact: true }).click()
  await phone.getByText('Live desk', { exact: true }).click()
  await expect(phone.getByText('Laptop online · connected', { exact: true })).toBeVisible()
  await expect(phone.getByRole('button', { name: 'Button', exact: true })).toHaveCSS('color', 'rgb(91, 200, 232)')
  await phone.getByRole('button', { name: 'Button', exact: true }).click()
  await expect(phone.getByText('Similar programs found — choose whether to reuse')).toBeVisible()
  await phone.getByLabel('Request ID').fill('pwa-browser')
  await phone.getByRole('radio').nth(1).check()
  await phone.getByRole('button', { name: 'Reuse and request execution', exact: true }).click()
  await expect(phone.getByText('COMPLETED', { exact: true })).toHaveCount(2)
  await page.getByRole('button', { name: 'Requests', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Recent requests' }).getByText('COMPLETED', { exact: true })).toHaveCount(2)
  expect((await (await request.get('http://127.0.0.1:18980/test/metrics')).json()).generation_calls - generationBefore).toBe(1)
  await phone.reload()
  await phone.getByText('Live desk', { exact: true }).click()
  await expect(phone.getByText('COMPLETED', { exact: true })).toHaveCount(2)
  expect(errors).toEqual([])
})
